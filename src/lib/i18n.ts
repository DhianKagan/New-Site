let activeLocale: Locale = 'uk';

function readStoredLocale(): Locale {
  try {
    return typeof window !== 'undefined' && window.localStorage.getItem(STORAGE_KEY) === 'ru' ? 'ru' : 'uk';
  } catch {
    return 'uk';
  }
}

export function getSavedLocale(): Locale {
  return readStoredLocale();
}

export function setActiveLocale(locale: Locale): void {
  activeLocale = locale;
  if (typeof window !== 'undefined') {
    try {
      window.localStorage.setItem(STORAGE_KEY, locale);
    } catch {
      // Language selection still applies for the current page if storage is unavailable.
    }
    document.documentElement.lang = locale;
  }
}

activeLocale = readStoredLocale();

export function getActiveLocale(): Locale {
  return activeLocale;
}

export function tr(text: string, russian?: string): string {
  return activeLocale === 'ru' ? russian ?? RU[text] ?? text : text;
}
